"""**哪些政策值得佔一個版位**(2026-08-05 使用者回饋)。

「不用高雄楠梓科技園區這種很地方性的資訊(可以有地方性的資訊,
但是要在台中彰化南投雲林為主)」。

讀者在台中與彰化。別縣市的單一園區停車場管理要點對他沒有決策價值,
而它佔掉的是一個真正政策的位置 —— 那一天的信裡,它排在
「投資臺灣生醫產業實施方案」與「新青安 3.0」之後,成為第三則深度解析。

**判準刻意要兩個條件同時成立**(別縣市 **且** 單一場所層級):
只看縣市名會誤殺(全國性法規常拿某個縣市當例子),
只看「管理要點」也會誤殺(中央法規也用這個詞)。
"""
from __future__ import annotations

#: 讀者在**台中與彰化**。地方性政策以中彰投雲為主 —— 其他縣市的
#: 單一園區、單一路段、單一場館規章沒有決策價值,而它佔掉的是一個
#: 真正政策的位置(2026-08-05 使用者:高雄楠梓停車場管理要點)。
_POLICY_HOME_REGIONS = ("台中", "臺中", "彰化", "南投", "雲林", "中彰投")
#: 出現這些字就是「單一場所層級」的規章。全國性法規不會用這些詞。
_POLICY_LOCAL_MARKERS = ("停車場", "管理要點", "使用規則", "收費標準",
                         "自治條例", "施行細則(地方)", "園區管理")
#: 其他縣市名。**只有同時滿足「別縣市」與「單一場所」才排除** ——
#: 單一條件會誤殺(全國性法規常提到某個縣市當例子)。
_POLICY_OTHER_REGIONS = ("高雄", "台南", "臺南", "桃園", "新竹", "苗栗",
                         "嘉義", "屏東", "宜蘭", "花蓮", "台東", "臺東",
                         "基隆", "澎湖", "金門", "馬祖", "新北", "台北", "臺北")


def is_out_of_area_local_policy(item: dict) -> bool:
    """別縣市的單一場所規章 → 不進「重大政策深度解析」。"""
    text = f"{item.get('topic') or ''}{item.get('title') or ''}"
    if any(r in text for r in _POLICY_HOME_REGIONS):
        return False
    return (any(r in text for r in _POLICY_OTHER_REGIONS)
            and any(m in text for m in _POLICY_LOCAL_MARKERS))


